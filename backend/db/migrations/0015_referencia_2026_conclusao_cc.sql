-- Referência 2026 (2026-09-29) e conclusão de CC pelo Gestor de CC.
--
-- referencia_2026: valor ANUAL de 2026 por unidade × CC × conta analítica, só
-- para comparação na plataforma (somente leitura, fora do documento do
-- orçamento 2027 — nunca é tocado por autosave/merge). 2026 = realizado de
-- jan a jul + orçado de ago a dez (arquivo "Corporativo 2026.xlsx", aba
-- Realizado para jan–jul e aba Orçado para ago–dez). Só Corporativo neste
-- primeiro input.
-- 'NAO_CLASSIFICADO': no arquivo, o realizado de jan–jul traz o total do CC
-- (linha do CC) maior do que a soma das classes de natureza — a diferença é
-- guardada nesta linha para o total do CC bater, sem atribuir a nenhuma conta.
--
-- conclusao_cc: CC marcado como concluído pelo Gestor de CC. Sem linha = em
-- preenchimento. Só o Admin FP&A libera (apaga a linha).
CREATE TABLE IF NOT EXISTS referencia_2026 (
  unidade_id   TEXT NOT NULL,
  cc_codigo    TEXT NOT NULL,
  conta_codigo TEXT NOT NULL,
  valor        NUMERIC(16,2) NOT NULL,
  PRIMARY KEY (unidade_id, cc_codigo, conta_codigo)
);

CREATE TABLE IF NOT EXISTS conclusao_cc (
  unidade_id    TEXT NOT NULL,
  cc_codigo     TEXT NOT NULL,
  concluido_em  TIMESTAMPTZ NOT NULL DEFAULT now(),
  concluido_por UUID REFERENCES usuarios(id),
  PRIMARY KEY (unidade_id, cc_codigo)
);

